export const LESSON_BY_ID: Record<string, LessonMeta & { moduleId: string }> = Object.fromEntries(
  MODULES.flatMap((m) => m.lessons.map((l) => [l.id, { ...l, moduleId: m.id }])),
);

/** Domain number a lesson belongs to for a given exam version (undefined if not on that exam). */
export function lessonDomain(lesson: LessonMeta, version: ExamVersion): number | undefined {
  if (version === 'v2.0') return lesson.v20;
  if (!lesson.v11 || lesson.v11.length === 0) return undefined;
  return Number(lesson.v11[0].split('.')[0]);
}

export function lessonInVersion(lesson: LessonMeta, version: ExamVersion): boolean {
  return lessonDomain(lesson, version) !== undefined;
}
