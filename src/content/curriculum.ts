/**
 * The WizardCCNA curriculum: a single learning path that covers the union of the
 * CCNA 200-301 v1.1 exam topics (current exam, last test date 2 Feb 2027) and the
 * CCNA 200-301 v2.0 exam topics (first test date 3 Feb 2027).
 *
 * Lessons are listed in recommended learning order. `v11` holds the official v1.1 topic codes a
 * lesson covers; `v20` holds the v2.0 domain number. A lesson with no `v11` codes is v2.0-only,
 * and a lesson with no `v20` domain is v1.1-only. `focus` is the coverage checklist: every item must
 * be taught in the slides and tested by flashcards/questions.
 */

export type ExamVersion = 'v1.1' | 'v2.0';

export interface ExamDomain {
  num: number;
  title: string;
  /** Percentage of the exam. */
  weight: number;
}

export interface ExamVersionInfo {
  id: ExamVersion;
  name: string;
  /** Inclusive date range (YYYY-MM-DD) in which this version is the live exam. */
  from?: string;
  until?: string;
  domains: ExamDomain[];
  durationMin: number;
  questionCount: number;
}

